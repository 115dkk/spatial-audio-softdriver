inline ULONG BioVolumeChannels(USHORT endpoint) {
    return endpoint == BIO_ENDPOINT_PRIMARY ? 8UL : 2UL;
}
inline BioFormatEntry BioDefaultPcm(USHORT endpoint) {
    return {0, BioGuid(STATICGUIDOF(KSDATAFORMAT_SUBTYPE_IEEE_FLOAT)),
        static_cast<USHORT>(BioVolumeChannels(endpoint)), 48000,
        static_cast<ULONG>(endpoint == BIO_ENDPOINT_PRIMARY ? KSAUDIO_SPEAKER_7POINT1_SURROUND : KSAUDIO_SPEAKER_STEREO),
        32, 32};
}
inline bool BioPcmEnabled(const BIO_PCM_FORMATS& pcm, bool floating) {
    return pcm.rates && (pcm.shapes & (floating ? 0x10U : 0x0fU)) &&
        (pcm.max_masked_channels || pcm.direct_channels);
}
